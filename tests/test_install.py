class TestIdempotence(InstallCase):
    def test_second_apply_is_a_clean_noop(self):
        for kind in ("launchd", "systemd"):
            self.runner = FakeRunner()
            self.assertEqual(self.run_install(kind, apply=True)[0], 0)
            before = {p: _readb(p) for p in self.tree() if os.path.isfile(p)}
            self.runner.calls.clear()
            rc, out, _ = self.run_install(kind, apply=True)
            self.assertEqual(rc, 0)
            self.assertIn("nothing to change", out)
            self.assertEqual(self.prompts, [], "no prompt when there is nothing to do")
            self.assertEqual(self.runner.mutating(), [])
            after = {p: _readb(p) for p in self.tree() if os.path.isfile(p)}
            self.assertEqual(before, after)

    def test_different_inputs_update_in_place(self):
        self.run_install("launchd", apply=True, interval=600)
        self.runner.calls.clear()
        rc, out, _ = self.run_install("launchd", apply=True, interval=300)
        self.assertEqual(rc, 0)
        self.assertEqual(plistlib.loads(_readb(self.plist))["StartInterval"], 300)
        # unload first, then load the new definition
        names = [c[1] for c in self.runner.mutating()]
        self.assertEqual(names, ["bootout", "bootstrap"])

    def test_unchanged_files_but_not_loaded_just_loads(self):
        self.run_install("launchd", apply=True)
        self.runner.loaded = False
        self.runner.calls.clear()
        self.run_install("launchd", apply=True)
        self.assertEqual([c[1] for c in self.runner.mutating()], ["bootstrap"])

    def test_foreign_file_is_never_overwritten(self):
        os.makedirs(os.path.dirname(self.plist))
        with open(self.plist, "w") as fh:
            fh.write("<plist>someone else's</plist>")
        rc, _, err = self.run_install("launchd", apply=True)
        self.assertNotEqual(rc, 0)
        self.assertIn("refusing", err)
        self.assertEqual(_read(self.plist), "<plist>someone else's</plist>")
        self.assertEqual(self.runner.mutating(), [])

    def test_symlink_at_target_is_never_followed(self):
        os.makedirs(os.path.dirname(self.plist))
        elsewhere = os.path.join(self.work, "elsewhere.plist")
        with open(elsewhere, "w") as fh:
            fh.write("untouched")
        os.symlink(elsewhere, self.plist)
        rc, _, err = self.run_install("launchd", apply=True)
        self.assertNotEqual(rc, 0)
        self.assertEqual(_read(elsewhere), "untouched")
        self.assertTrue(os.path.islink(self.plist))

    def test_failed_load_is_reported_non_zero(self):
        rc, _, err = self.run_install("launchd", apply=True,
                                      runner=FakeRunner(fail_on="bootstrap"))
        self.assertNotEqual(rc, 0)
        self.assertIn("bootstrap", err)


class TestUninstall(InstallCase):
    def test_uninstall_unloads_and_removes_macos_files(self):
        self.run_install("launchd", apply=True)
        self.runner.calls.clear()
        rc, out, err = self.run_install("launchd", uninstall=True)
