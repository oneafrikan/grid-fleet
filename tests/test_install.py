def _read(path):
    with open(path, "r") as fh:
        return fh.read()


def _readb(path):
    with open(path, "rb") as fh:
        return fh.read()


class FakeRunner:
    """Stands in for launchctl/systemctl. Records every argv; tracks a loaded/enabled flag
    the way the real tools would, so idempotence and uninstall can be observed."""

    def __init__(self, loaded=False, fail_on=None):
        self.calls = []
        self.loaded = loaded
        self.fail_on = fail_on  # substring of a command that should fail (exit 1)

    def __call__(self, argv):
        argv = list(argv)
        self.calls.append(argv)
        line = " ".join(argv)
        if self.fail_on and self.fail_on in line:
            return 1, "synthetic failure"
        if argv[:2] == ["launchctl", "print"] or "is-enabled" in argv:
            return (0 if self.loaded else 1), ""
        if "bootstrap" in argv or "enable" in argv:
            self.loaded = True
        if "bootout" in argv or "disable" in argv:
            self.loaded = False
        return 0, ""

    def mutating(self):
        """Calls other than the read-only queries."""
        return [c for c in self.calls
                if c[:2] != ["launchctl", "print"] and "is-enabled" not in c]


class InstallCase(unittest.TestCase):
    def setUp(self):
        self.work = tempfile.mkdtemp(prefix="gf-install-")
        self.addCleanup(shutil.rmtree, self.work, True)
        self.home = os.path.join(self.work, "home")
        os.makedirs(self.home)
        self.state = os.path.join(self.work, "state")
        self.env = {"HOME": self.home, "PATH": SYNTH_PATH}
        self.config = cfg.Config(hub="hub-alias", interval_s=600,
                                 config_path="/synth/config.json", state_dir=self.state)
        self.runner = FakeRunner()

    def args(self, **kw):
        base = dict(interval=None, apply=False, uninstall=False)
        base.update(kw)
        return argparse.Namespace(**base)

    def run_install(self, kind="launchd", config=None, runner=None, tty=True, answer="y",
                    env=None, **argkw):
        """Call install_main with every side effect injected; return (rc, stdout, stderr)."""
        out, err = io.StringIO(), io.StringIO()
        prompts = []

        def prompt(text):
            prompts.append(text)
            return answer

        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            rc = install.install_main(
                config or self.config, self.args(**argkw),
                runner=runner or self.runner, env=env or self.env,
                platform="darwin" if kind == "launchd" else "linux",
                python=PY, script=SCRIPT, uid=UID,
                is_tty=lambda: tty, prompt=prompt)
        self.prompts = prompts
        return rc, out.getvalue(), err.getvalue()

    # -- paths ---------------------------------------------------------------
    @property
    def plist(self):
        return os.path.join(self.home, "Library", "LaunchAgents", "io.grid-fleet.timer.plist")

    @property
    def sd_dir(self):
        return os.path.join(self.home, ".config", "systemd", "user")

    def tree(self):
        """Every path under the temp work dir, to prove nothing else appears."""
        found = []
        for root, dirs, files in os.walk(self.work):
            found += [os.path.join(root, n) for n in dirs + files]
        return sorted(found)


class TestRender(unittest.TestCase):
    """Pure render functions: golden text, no filesystem."""

    def test_plist_golden(self):
        self.assertEqual(
            install.render_launchd_plist(PY, SCRIPT, SYNTH_PATH, 600, "/synth/state/timer.log"),
            GOLDEN_PLIST)

    def test_plist_parses_and_has_interval_paths_and_path(self):
        text = install.render_launchd_plist(PY, SCRIPT, SYNTH_PATH, 300, "/synth/state/timer.log")
        data = plistlib.loads(text.encode("utf-8"))  # the marker comment must not break parsing
        self.assertEqual(data["StartInterval"], 300)
        self.assertEqual(data["EnvironmentVariables"]["PATH"], SYNTH_PATH)
        shell = data["ProgramArguments"]
        self.assertEqual(shell[:2], ["/bin/sh", "-c"])
        self.assertIn(PY + " " + SCRIPT + " collect && " + PY + " " + SCRIPT + " push", shell[2])

    def test_service_and_timer_golden(self):
        self.assertEqual(install.render_systemd_service(PY, SCRIPT, SYNTH_PATH), GOLDEN_SERVICE)
        self.assertEqual(install.render_systemd_timer(900), GOLDEN_TIMER)

    def test_render_is_deterministic(self):
        a = install.render_launchd_plist(PY, SCRIPT, SYNTH_PATH, 600, "/l")
        self.assertEqual(a, install.render_launchd_plist(PY, SCRIPT, SYNTH_PATH, 600, "/l"))

    def test_every_generated_file_carries_the_marker_first(self):
        for text in (install.render_launchd_plist(PY, SCRIPT, SYNTH_PATH, 600, "/l"),
                     install.render_systemd_service(PY, SCRIPT, SYNTH_PATH),
                     install.render_systemd_timer(600)):
            self.assertIn(install.MARKER, text[:install._MARKER_SCAN_BYTES])

    def test_paths_with_spaces_and_specials_are_quoted(self):
        # systemd expands % and $ and splits on spaces; the shell form must quote too.
        svc = install.render_systemd_service("/o pt/py%3", "/s$rv/gf", "/a b:/c%d")
        self.assertIn('ExecStart="/o pt/py%%3" /s$$rv/gf collect', svc)
        self.assertIn('Environment="PATH=/a b:/c%%d"', svc)
        plist = plistlib.loads(install.render_launchd_plist(
            "/o pt/py", "/s rv/gf", "/p", 600, "/l").encode("utf-8"))
        self.assertIn("'/o pt/py' '/s rv/gf' collect", plist["ProgramArguments"][2])

    def test_control_characters_are_refused(self):
        with self.assertRaises(install.InstallError):
            install.render_systemd_service(PY, SCRIPT, "/a\n[Service]\nExecStart=/evil")
        with self.assertRaises(install.InstallError):
            install.render_launchd_plist(PY, SCRIPT, "/a\nb", 600, "/l")


