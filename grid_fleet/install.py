_STYLES = [(indent, ascii_, nl) for indent in (2, 4, "\t", None)
           for ascii_ in (False, True) for nl in ("\n", "")]


def _dump(data, style) -> str:
    indent, ascii_, nl = style
    return json.dumps(data, indent=indent, ensure_ascii=ascii_) + nl


def _pick_style(data, text: str):
    """Find the JSON layout that reproduces `text` byte-for-byte, so the rewrite does not
    reformat the user's file. Returns (style, exact); falls back to 2-space + newline."""
    for style in _STYLES:
        if _dump(data, style) == text:
            return style, True
    return (2, False, "\n"), False


# What a rewrite in the fallback layout can change. Shown to the user before the "y", so it
# must list what really happens, not only the good news.
_REWRITE_NOTE = ("note: %s is not in a layout grid-fleet can reproduce, so it will be "
                 "rewritten as 2-space JSON. Values and key order are kept, but duplicate keys "
                 "are dropped (the last one wins), CRLF line endings become LF, and number "
                 "spellings may be normalised (e.g. 1.0e2 becomes 100.0)")


def _rewrite_note(path: str) -> str:
    """The note above, naming the file actually being rewritten (settings.json for the
    statusLine edit, the grid-fleet config for the install config write). Basename only:
    the full path is already printed by the plan."""
    return _REWRITE_NOTE % os.path.basename(path)


def _has_nonfinite(obj) -> bool:
    """True if any number in the parsed JSON is inf/nan. json.loads accepts `1e999`,
    `NaN` and `Infinity`; json.dumps would write them back as bare `Infinity`/`NaN`,
    which is not valid JSON, so a lossy rewrite must refuse instead."""
    stack = [obj]
    while stack:
        cur = stack.pop()
        if isinstance(cur, float) and (cur != cur or cur in (float("inf"), float("-inf"))):
            return True
        if isinstance(cur, dict):
            stack.extend(cur.values())
        elif isinstance(cur, list):
            stack.extend(cur)
    return False


def _render(data, style, exact, path: str):
    """(new text, layout note) for the edited settings, or InstallError.

    Refuses, before anything is written, when the rewrite could not be faithful: a number
    that would come back as Infinity/NaN (only possible when the layout is not reproduced
    byte-for-byte), or text that cannot be encoded as UTF-8 (a lone-surrogate escape such as
    "\\ud800" in a non-reproducible layout)."""
    if not exact and _has_nonfinite(data):
        raise InstallError("%s contains a number (e.g. 1e999) that cannot be rewritten as valid "
                           "JSON; left untouched, fix or remove it first" % path)
    text = _dump(data, style)
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        raise InstallError("%s contains text that cannot be written as UTF-8 (a lone surrogate "
                           "escape?); left untouched" % path)
    return text, ("" if exact else _rewrite_note(path))


def _read_json_object(path: str, what: str):
    """(raw bytes, parsed dict) or InstallError. Key order is kept (dicts are ordered)."""
    try:
        with open(path, "rb") as fh:
            raw = fh.read()
    except FileNotFoundError:
        raise InstallError("%s not found: %s" % (what, path))
    except OSError as exc:
        raise InstallError("cannot read %s %s: %s" % (what, path, exc.strerror or exc))
    try:
        data = json.loads(raw.decode("utf-8"))
    except ValueError as exc:  # includes UnicodeDecodeError and JSONDecodeError
        raise InstallError("%s is not valid JSON, left untouched: %s (%s)" % (what, path, exc))
    if not isinstance(data, dict):
        raise InstallError("%s is not a JSON object, left untouched: %s" % (what, path))
    return raw, data


def _mode_of(path: str) -> int:
    return os.stat(path).st_mode & 0o777


def _backup(path: str, raw: bytes) -> str:
    """Byte copy of the settings file next to it, never overwriting one.

    The backup's mode is the original's mode & 0600: settings.json can hold secrets
    (env values, tokens), so a backup is never group/world-readable even when the
    original is, and never wider than the original. (Backups are not pruned.)
    """
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(cfg.now()))
    mode = _mode_of(path) & 0o600
    for n in range(100):
        dest = "%s%s%s%s" % (path, BACKUP_INFIX, stamp, "" if n == 0 else "-%d" % n)
        try:
            fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            continue
        with os.fdopen(fd, "wb") as fh:
            fh.write(raw)
        os.chmod(dest, mode)
        return dest
    raise InstallError("could not find a free backup name for %s" % path)


def _write_json_file(path: str, data: dict, style, mode: int) -> None:
    """Atomic rewrite through symlinks: a dotfile-managed symlink stays a symlink."""
    _write_atomic(os.path.realpath(path), _dump(data, style), mode)


# -- building the edit ---------------------------------------------------------------------


def _show(value: Optional[str]) -> str:
    """Exact rendering of a command for the diff: JSON string syntax shows every escape."""
    return _NO_STATUSLINE if value is None else json.dumps(value, ensure_ascii=False)


def _statusline_command(data: dict):
    """(statusLine value, its command or None). InstallError for a shape we will not guess."""
    sl = data.get("statusLine")
    if sl is None:
        return None, None
    if (isinstance(sl, dict) and isinstance(sl.get("command"), str)
            and sl.get("type", "command") == "command"):
        return sl, sl["command"]
    raise InstallError("statusLine in settings.json has a shape grid-fleet does not handle "
                       "(expected {\"type\": \"command\", \"command\": \"...\"}); not changing it")


def plan_statusline_install(path: str, python: str, script: str) -> StatuslineEdit:
    """Read-only. The edit that wraps the current statusLine in the tap."""
    raw, data = _read_json_object(path, "settings file")
    style, exact = _pick_style(data, raw.decode("utf-8"))
    sl, current = _statusline_command(data)
    if current is not None and is_tap_command(current):
        # Never double-wrap. (If the clone moved, the old wrapper keeps pointing at the old
        # path: `--uninstall` then `--statusline` re-points it.) Say so loudly: a wrapper
        # whose script is gone makes the statusLine print nothing, silently.
        note = ""
        old_script = _tap_script(current)
        if old_script is not None and not os.path.exists(old_script):
            note = ("WARNING: the existing wrapper points at %s, which does not exist (moved or "
                    "deleted clone?), so the statusLine is currently blank. Nothing was changed; "
                    "to re-point it run `grid-fleet install --statusline --uninstall`, then "
                    "`grid-fleet install --statusline`" % old_script)
        return StatuslineEdit("noop", "statusLine is already wrapped by grid-fleet; nothing "
                              "to change", path, raw, None, current, current, note, None)
    wrapped = tap_command(python, script, current)
    new_sl = {"type": "command", "command": wrapped} if sl is None else dict(sl, command=wrapped)
    new_data = dict(data)  # a copy keeps key order; an existing statusLine stays in place
    new_data["statusLine"] = new_sl
    new_text, note = _render(new_data, style, exact, path)
    return StatuslineEdit("change", "", path, raw, new_text, current, wrapped, note, current)


def _refuse(path: str, message: str) -> StatuslineEdit:
    return StatuslineEdit("refuse", "statusLine NOT restored: %s" % message, path, b"",
                          None, None, None, "", None)


def plan_statusline_restore(path: str, saved: Optional[str]) -> StatuslineEdit:
    """Read-only. The edit that puts the original statusLine back.

    The original embedded in the wrapper in THIS settings file is the only source that is
    certain to belong to this Claude dir, so it decides. `saved` (config
    statusline_original) is one slot shared by every Claude dir using the config; it is
    never used to replace what the wrapper says. It only (a) tells an empty-string
    original from "no statusLine" (both are written as a bare `tap --`), and (b) is shown
    in a note or in the refusal when it disagrees. A wrapper whose tail is not a form
    grid-fleet writes (hand-edited, or a lookalike) is refused untouched, whatever is
    saved: a stale slot must never silently replace it.
    """
    try:
        raw, data = _read_json_object(path, "settings file")
    except InstallError as exc:
        if not os.path.lexists(path):
            return StatuslineEdit("noop", "no settings file, nothing to restore: %s" % path,
                                  path, b"", None, None, None, "", None)
        return _refuse(path, str(exc))
    style, exact = _pick_style(data, raw.decode("utf-8"))
    try:
        sl, current = _statusline_command(data)
    except InstallError:  # a shape we could never have written: not ours, leave it
        sl, current = None, None
    if current is None or not is_tap_command(current):
        return StatuslineEdit("noop", "statusLine is not wrapped by grid-fleet; nothing to "
                              "restore", path, raw, None, current, current, "", None)
    try:
        try:
            original = _original_from_tap(current)
        except InstallError as exc:
            detail = "%s. Nothing was changed." % exc
            if saved is not None:
                detail += (" The config's %s is %s but is not used for a wrapper that does not "
                           "match what grid-fleet writes." % (CONFIG_KEY, _show(saved)))
            raise InstallError(detail + " To proceed, set statusLine.command in %s by hand, "
                               "then re-run." % path)
        notes = []
        if original is None and saved == "":
            original = ""  # a bare `tap --` plus a saved "": the original command was empty
        elif saved is not None and saved != original:
            notes.append("note: the config's %s (%s) differs from the original embedded in this "
                         "wrapper (%s); using the wrapper's. (The config keeps one slot shared by "
                         "all Claude dirs, so another dir's install can overwrite it.)"
                         % (CONFIG_KEY, _show(saved), _show(original)))
        new_data = dict(data)
        if original is None:
            # We created the whole statusLine; remove it, but only if nobody added to it.
            if set(sl) - {"type", "command"}:
                raise InstallError("statusLine has extra keys and no saved original; "
                                   "restore it by hand")
            del new_data["statusLine"]
        else:
            new_data["statusLine"] = dict(sl, command=original)
        new_text, layout_note = _render(new_data, style, exact, path)
        if layout_note:
            notes.append(layout_note)
    except InstallError as exc:
        return StatuslineEdit("refuse", "statusLine NOT restored: %s" % exc, path, raw,
                              None, None, None, "", None)
    return StatuslineEdit("change", "", path, raw, new_text, current,
                          original, "\n  ".join(notes), original)


# -- applying ------------------------------------------------------------------------------


def _set_config_original(config_path: str, value: Optional[str], create: bool,
                         only_if: Optional[str] = None) -> None:
    """Set (or clear, value=None) `statusline_original` in the config file, keeping every
    other key. Raises InstallError if the file is unusable, OSError on write failure.

    only_if: when given, write only if the slot currently holds exactly this value. Restore
    uses it so that clearing the slot never discards a value another Claude dir's install
    saved there (the slot is shared; see the flow comment above)."""
    if os.path.lexists(config_path):
        raw, data = _read_json_object(config_path, "config file")
        style, _exact = _pick_style(data, raw.decode("utf-8"))
        mode = _mode_of(config_path)
    elif create:
        data, style, mode = {"schema": cfg.SCHEMA}, (2, False, "\n"), 0o600
    else:
        return
    if only_if is not None and data.get(CONFIG_KEY) != only_if:
        return
    data[CONFIG_KEY] = value
    # A config dir this tool has to create (first install) is private, like the file in it.
    _makedirs_private(os.path.dirname(os.path.realpath(config_path)))
    _write_json_file(config_path, data, style, mode)


def _apply_statusline_edit(edit: StatuslineEdit, config_path: str, restoring: bool) -> str:
    """Perform a confirmed edit; returns the backup path. Raises InstallError / OSError.

    ValueError (UnicodeEncodeError on a lone surrogate) is turned into InstallError: the
    plan already refuses such text, this is the belt for anything that slips past it."""
    # The user (or Claude Code) may have saved settings.json while we waited for the "y".
    try:
        with open(edit.path, "rb") as fh:
            still = fh.read()
    except OSError as exc:
        raise InstallError("cannot re-read %s: %s" % (edit.path, exc.strerror or exc))
    if still != edit.raw:
        raise InstallError("%s changed while waiting for confirmation; nothing was changed, "
                           "re-run" % edit.path)
    mode = _mode_of(edit.path)
    try:
        edit.new_text.encode("utf-8")  # fail before the backup, not after
    except ValueError as exc:
        raise InstallError("%s cannot be written, left untouched: %s" % (edit.path, exc))
    backup = _backup(edit.path, edit.raw)
    try:
        _write_atomic(os.path.realpath(edit.path), edit.new_text, mode)
    except ValueError as exc:
        raise InstallError("%s cannot be written, left untouched: %s" % (edit.path, exc))
    # Config second: settings are already right, and the wrapper embeds the original, so a
    # failure here costs only the informational slot.
    try:
        if restoring:
            # original None = we had created the statusLine, so this dir owns no saved
            # value and the slot (if any) belongs to someone else: leave it alone.
            if edit.original is not None:
                _set_config_original(config_path, None, create=False, only_if=edit.original)
        else:
            _set_config_original(config_path, edit.original, create=True)
    except (InstallError, OSError, ValueError) as exc:
        sys.stderr.write("grid-fleet install: statusLine %s, but could not update %s in the "
                         "config: %s\n" % ("restored" if restoring else "updated", CONFIG_KEY, exc))
    return backup


def _print_edit(edit: StatuslineEdit, config_path: str, restoring: bool) -> None:
    """The exact before/after the user is asked to confirm."""
    out = sys.stdout
    out.write("%s\n  settings: %s\n  statusLine.command\n    before: %s\n    after:  %s\n"
              % ("statusLine restore" if restoring else "grid-fleet install --statusline",
                 edit.path, _show(edit.before),
                 "(statusLine removed)" if edit.after is None else _show(edit.after)))
    out.write("  all other settings: unchanged\n")
    out.write("  backup: %s<UTC time> (written first)\n" % (edit.path + BACKUP_INFIX))
    if not restoring:
        out.write("  original saved to %s as %s\n" % (config_path, CONFIG_KEY))
    if edit.note:
        out.write("  %s\n" % edit.note)  # may hold several lines, already indented


def _statusline_main(config, args, explicit_interval, env, runner, python, script, uid,
                     is_tty, prompt) -> int:
    """`install --statusline [--uninstall]`: the statusLine half only, no timers touched."""
    if explicit_interval is not None:
        sys.stderr.write("grid-fleet install: --interval does not apply to --statusline\n")
        return EXIT_USAGE
    if getattr(args, "uninstall", False):
        sl = plan_statusline_restore(settings_path(config, env), _saved_original(config))
        return _run_uninstall(None, [], uid, runner, is_tty, prompt, sl, config.config_path,
                              timers=False)
    if not python or not os.path.isabs(python) or not os.path.isabs(script):
        sys.stderr.write("grid-fleet install: need absolute paths for python and script "
                         "(got %r, %r)\n" % (python, script))
        return EXIT_USAGE
    return _statusline_install(config, env, python, script, is_tty, prompt)


def _statusline_install(config, env, python, script, is_tty, prompt) -> int:
    path = settings_path(config, env)
    try:
        edit = plan_statusline_install(path, python, script)
        if os.path.lexists(config.config_path):  # fail now, not after the "y"
            _read_json_object(config.config_path, "config file")
    except InstallError as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    if edit.action == "noop":
        sys.stdout.write("%s\n" % edit.message)
        if edit.note:  # e.g. the wrapper points at a script that no longer exists
            sys.stderr.write("grid-fleet install: %s\n" % edit.note)
        return EXIT_OK
    _print_edit(edit, config.config_path, restoring=False)
    if not is_tty():
        sys.stderr.write("grid-fleet install: --statusline needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    try:
        backup = _apply_statusline_edit(edit, config.config_path, restoring=False)
    except (InstallError, OSError, ValueError) as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    sys.stdout.write("statusLine now runs the tap\nbackup: %s\nundo: grid-fleet install "
                     "--uninstall\n" % backup)
    return EXIT_OK


# --- config keys (interval_s, hub, account) ---------------------------------------------------
#
# Flow for `install --apply`:  plan the config edit (read-only) -> print before/after ->
# refuse if no hub -> TTY + "y" -> write config ATOMICALLY -> only then load the timer.
# Config goes first so the very first tick (launchd RunAtLoad, systemd OnActiveSec) already
# sees the right hub. Everything up to the confirmation is read-only.

CONFIG_KEYS = ("interval_s", "hub", "account")
_ABSENT = object()  # "key not in the file", distinct from any JSON value (incl. null)

# Account label rules. The hub shows the label as printable ASCII, at most 32 chars, and
# falls back to "default" for an empty one (hub._account_label); install refuses anything
# the hub would have to rewrite, so what is stored is what is displayed. Kept as local
# constants (not imported from hub) so the installer does not depend on hub internals.
ACCOUNT_LABEL_MAX = 32

# One planned config edit. `raw` is the file's bytes when it existed (None = will be
# created); `new_text` is only meaningful when `changed`.
ConfigEdit = collections.namedtuple(
    "ConfigEdit", "path raw created changed before after new_data style mode new_text note")


def validate_account(value: object) -> Optional[str]:
    """None if `value` is an account label the hub shows unchanged, else the reason."""
    if not isinstance(value, str) or not value:
        return "must be a non-empty label"
    if value != value.strip():
        return "must not start or end with whitespace"
    if any(not (" " <= c <= "~") for c in value):
        return "may only contain printable ASCII"
    if len(value) > ACCOUNT_LABEL_MAX:
        return "must be at most %d characters" % ACCOUNT_LABEL_MAX
    return None


def _same_value(a, b) -> bool:
    """Equality that does not treat True as 1 (config values are strictly typed)."""
    return type(a) is type(b) and a == b


def _show_value(value) -> str:
    return "(absent)" if value is _ABSENT else json.dumps(value)


def plan_config_edit(config, interval_s: int, hub: str, account: str) -> ConfigEdit:
    """Decide what `install --apply` would do to the config file. Read-only.

    Raises InstallError (file untouched) for an unreadable / invalid-JSON / non-object file
    or an unknown `schema`: the file is the user's and we do not guess at its meaning.
    An existing file keeps every other key (known or unknown), key order and, when it can
    be reproduced, its exact layout; the three keys are replaced in place or appended in
    the order interval_s, hub, account. A missing file is created with schema, host_name
    (config.host_name, i.e. derived exactly as collect derives it) and the three keys.
    host_name is NOT added to an existing file: collect already derives it at load time.
    """
    path = config.config_path
    desired = {"interval_s": interval_s, "hub": hub, "account": account}
    if os.path.lexists(path):
        raw, data = _read_json_object(path, "config file")
        schema = data.get("schema")
        if isinstance(schema, bool) or schema != cfg.SCHEMA:  # True == 1 in Python
            raise InstallError("config file %s has unsupported schema %r (expected %d); "
                               "left untouched" % (path, schema, cfg.SCHEMA))
        style, exact = _pick_style(data, raw.decode("utf-8"))
        mode, created = _mode_of(path), False
    else:
        raw, created, exact = None, True, True
        data = {"schema": cfg.SCHEMA, "host_name": config.host_name}
        style, mode = (2, False, "\n"), 0o600  # private: a fresh file is 0600
    before = {k: data.get(k, _ABSENT) for k in CONFIG_KEYS}
    changed = created or not all(_same_value(before[k], desired[k]) for k in CONFIG_KEYS)
    new_data = dict(data)  # a dict keeps order: existing keys stay put, new ones append
    new_data.update(desired)
    new_text, note = "", ""
    if changed:
        new_text, note = _render(new_data, style, exact, path)
    return ConfigEdit(path, raw, created, changed, before, desired, new_data, style, mode,
                      new_text, note)


def config_plan_lines(edit: ConfigEdit) -> List[str]:
    """The 'config:' block of the plan: exact before/after of just the three keys."""
    state = ("will be created" if edit.created
             else "will be updated" if edit.changed else "unchanged")
    lines = ["config: %s (%s)" % (edit.path, state)]
    for key in CONFIG_KEYS:
        old, new = edit.before[key], edit.after[key]
        if _same_value(old, new):
            lines.append("  %-10s %s (unchanged)" % (key, _show_value(new)))
        else:
            lines.append("  %-10s %s -> %s" % (key, _show_value(old), _show_value(new)))
    if edit.changed:
        lines.append("  all other config keys: unchanged")
        if edit.note:
            lines.append("  " + edit.note)
    return lines


def _apply_config_edit(edit: ConfigEdit) -> None:
    """Write a planned config edit atomically. Raises InstallError / OSError.

    The file may have been edited while we waited for the "y"; if its bytes changed since
    the plan, stop and write nothing (same rule as the settings.json edit).
    """
    if edit.created:
        if os.path.lexists(edit.path):
            raise InstallError("config file %s appeared while waiting for confirmation; "
                               "nothing was changed, re-run" % edit.path)
    else:
        try:
            with open(edit.path, "rb") as fh:
                still = fh.read()
        except OSError as exc:
            raise InstallError("cannot re-read %s: %s" % (edit.path, exc.strerror or exc))
        if still != edit.raw:
            raise InstallError("config file %s changed while waiting for confirmation; "
                               "nothing was changed, re-run" % edit.path)
    # A config dir this tool has to create is private (0700); an existing dir is never
    # chmod-ed. Resolved through symlinks, like the write, so a dotfile-managed link works.
    _makedirs_private(os.path.dirname(os.path.realpath(edit.path)))
    try:
        # _write_atomic: temp file in the same dir + os.replace, so a failure leaves the old file.
        _write_json_file(edit.path, edit.new_data, edit.style, edit.mode)
    except ValueError as exc:  # e.g. text that cannot be encoded as UTF-8
        raise InstallError("config file %s cannot be written, left untouched: %s" % (edit.path, exc))


