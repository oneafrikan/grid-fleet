"""Timer install for `grid-fleet install` (Group 8, timers only).

Owner: Group 8 unit (core-platform-engineer). Entry point used by cli.py:
install_main(config, args) -> int. OS-specific code is isolated here
(CLAUDE.md hard constraint).

What this module does
---------------------
  macOS : one user LaunchAgent plist under ~/Library/LaunchAgents, loaded with
          `launchctl bootstrap`.
  Linux : one user .service + .timer under the user systemd dir, enabled with
          `systemctl --user enable --now`. `loginctl enable-linger` is only
          ever PRINTED as a note, never run.
  Each tick runs `collect` then `push` (push only if collect succeeded).

statusLine tap (`install --statusline`, task 8.3)
-------------------------------------------------
  Rewrites `statusLine.command` in <claude dir>/settings.json so the tap wraps the
  user's original command, and saves the original in grid-fleet's config
  (`statusline_original`). `--uninstall` puts it back byte-for-byte. It is the ONLY
  code path that ever writes settings.json, and only after printing the exact
  before/after, a TTY and a "y". See the "statusLine" section below.

What it deliberately does NOT do
--------------------------------
  Writing hub/account into the config file is not done here: `--interval`
  only affects the timer (see the mismatch warning in `_warnings`). The one config
  key install writes is `statusline_original`.

Safety model
------------
  * Default is PLAN: prints files + commands, changes nothing, runs nothing.
  * `--apply`, `--statusline` and `--uninstall` need an interactive TTY and a "y" answer.
  * Render functions are pure (return text) and unit-tested. The only side
    effects are file writes/removals under the user's own unit dirs and calls
    to `launchctl`/`systemctl` through an injectable runner.
  * Every file we write starts with a generated-file marker. We only ever
    overwrite or delete a file that carries the marker, and never a symlink:
    a foreign file or symlink at our path is reported and left alone.
  * No root: everything is per-user.
"""

import argparse
import collections
import json
import os
import plistlib
import shlex
import subprocess
import sys
import tempfile
import time
from typing import Callable, List, Mapping, Optional, Sequence, Tuple

from grid_fleet import config as cfg

# Reverse-DNS style label for the launchd job; also the file stem on macOS.
LAUNCHD_LABEL = "io.grid-fleet.timer"
# systemd unit stem: grid-fleet.service / grid-fleet.timer.
SYSTEMD_STEM = "grid-fleet"

# First line(s) of every file we write. Presence of this string is the ONLY thing
# that lets us overwrite or delete a file (ownership test).
MARKER = "Generated by grid-fleet install"
_MARKER_SCAN_BYTES = 1024

# Used if PATH is unset at install time: the scheduler's own minimal default.
FALLBACK_PATH = "/usr/bin:/bin"
# First tick after the timer starts (Linux). Later ticks follow `interval_s`.
FIRST_RUN_DELAY_S = 30

EXIT_OK = 0
EXIT_REFUSED = 1  # non-TTY, declined, foreign file in the way, command failed
EXIT_USAGE = 2    # bad --interval, unsupported platform

LINGER_NOTE = (
    "note: on Linux the user systemd manager stops when you log out, so the timer "
    "only runs while you are logged in unless lingering is enabled. To keep it "
    "running while logged out (headless boxes), run once yourself: "
    "`loginctl enable-linger $USER`. grid-fleet never runs this."
)

# Runner contract: argv -> (returncode, combined output). Never raises for a
# missing binary: returns 127 so callers treat it as a failed command.
Runner = Callable[[Sequence[str]], Tuple[int, str]]


class InstallError(Exception):
    """User-facing install problem; message goes to stderr."""


# --- pure rendering -----------------------------------------------------------


def _check_text(label: str, value: str) -> str:
    """Reject values that could break out of a unit/plist line (newlines, NULs)."""
    if any(ord(c) < 32 for c in value):
        raise InstallError("%s contains a control character; refusing to write it" % label)
    return value


def _marker_line() -> str:
    return "%s; do not edit; regenerate by re-running `grid-fleet install` with apply." % MARKER


def _tick_command(python: str, script: str) -> str:
    """Shell form of one tick: collect, then push only if collect succeeded."""
    base = "%s %s" % (shlex.quote(python), shlex.quote(script))
    return "%s collect && %s push" % (base, base)


def render_launchd_plist(python: str, script: str, path_env: str, interval_s: int,
                         log_path: str) -> str:
    """The LaunchAgent plist as text. Pure; plistlib output is deterministic (sorted keys).

    ProgramArguments uses an absolute /bin/sh so `collect && push` needs no PATH
    lookup; the interpreter and script are absolute too. PATH is the install-time
    value so `ssh` and `claude` resolve under launchd's minimal environment.
    """
    for label, value in (("python", python), ("script", script), ("PATH", path_env),
                         ("log path", log_path)):
        _check_text(label, value)
    body = plistlib.dumps({
        "Label": LAUNCHD_LABEL,
        "ProgramArguments": ["/bin/sh", "-c", _tick_command(python, script)],
        "StartInterval": interval_s,
        # Run once at load too, so a fresh install shows up on the hub immediately.
        "RunAtLoad": True,
        "EnvironmentVariables": {"PATH": path_env},
        # launchd has no journal: keep stderr (push failures) where the user can find it.
        "StandardOutPath": log_path,
        "StandardErrorPath": log_path,
    }).decode("utf-8")
    # XML comment between the DOCTYPE and <plist> carries the ownership marker.
    return body.replace("<plist ", "<!-- %s -->\n<plist " % _marker_line(), 1)


def _sd_arg(value: str) -> str:
    """Quote one ExecStart= word. systemd expands `%` specifiers and `$` vars there."""
    esc = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    if any(c.isspace() or c in "'\"" for c in value):
        return '"%s"' % esc
    return esc


def render_systemd_service(python: str, script: str, path_env: str) -> str:
    """The user .service. Type=oneshot with two ExecStart lines runs them in order and
    stops at the first failure, which is the same collect-then-push-if-ok rule as launchd."""
    for label, value in (("python", python), ("script", script), ("PATH", path_env)):
        _check_text(label, value)
    py, sc = _sd_arg(python), _sd_arg(script)
    # Environment= takes the whole assignment quoted; only `%`, `\` and `"` are special.
    env = ("PATH=" + path_env).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return "\n".join([
        "# " + _marker_line(),
        "[Unit]",
        "Description=grid-fleet: collect and push a snapshot",
        "",
        "[Service]",
        "Type=oneshot",
        'Environment="%s"' % env,
        "ExecStart=%s %s collect" % (py, sc),
        "ExecStart=%s %s push" % (py, sc),
        "",
    ])


def render_systemd_timer(interval_s: int) -> str:
    """The user .timer. OnActiveSec fires the first run shortly after the timer starts
    (OnUnitActiveSec alone would never fire: it counts from the service's last run)."""
    return "\n".join([
        "# " + _marker_line(),
        "[Unit]",
        "Description=grid-fleet: run collect and push every %d s" % interval_s,
        "",
        "[Timer]",
        "OnActiveSec=%ds" % FIRST_RUN_DELAY_S,
        "OnUnitActiveSec=%ds" % interval_s,
        "Unit=%s.service" % SYSTEMD_STEM,
        "",
        "[Install]",
        "WantedBy=timers.target",
        "",
    ])


# --- paths / plan ---------------------------------------------------------------


def _home(env: Mapping[str, str]) -> str:
    return env.get("HOME") or os.path.expanduser("~")


def systemd_user_dir(env: Mapping[str, str]) -> str:
    # XDG spec: only an absolute XDG_CONFIG_HOME counts.
    xdg = env.get("XDG_CONFIG_HOME", "")
    base = xdg if xdg and os.path.isabs(xdg) else os.path.join(_home(env), ".config")
    return os.path.join(base, "systemd", "user")


def launchd_dir(env: Mapping[str, str]) -> str:
    return os.path.join(_home(env), "Library", "LaunchAgents")


def default_script() -> str:
    """Absolute path of bin/grid-fleet in the clone this module was imported from."""
    root = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
    return os.path.join(root, "bin", "grid-fleet")


def system_kind(platform: str) -> str:
    """Map sys.platform to 'launchd' / 'systemd'; anything else is unsupported."""
    if platform == "darwin":
        return "launchd"
    if platform.startswith("linux"):
        return "systemd"
    raise InstallError("unsupported platform %r (macOS and Linux only)" % platform)


def render_files(kind: str, *, python: str, script: str, path_env: str, interval_s: int,
                 env: Mapping[str, str], log_path: str) -> List[Tuple[str, str]]:
    """[(absolute path, text)] for every file the install owns on this platform."""
    if kind == "launchd":
        return [(os.path.join(launchd_dir(env), LAUNCHD_LABEL + ".plist"),
                 render_launchd_plist(python, script, path_env, interval_s, log_path))]
    d = systemd_user_dir(env)
    return [
        (os.path.join(d, SYSTEMD_STEM + ".service"),
         render_systemd_service(python, script, path_env)),
        (os.path.join(d, SYSTEMD_STEM + ".timer"), render_systemd_timer(interval_s)),
    ]


def file_state(path: str, text: str) -> str:
    """new | unchanged | update | foreign | symlink  (read-only).

    foreign = exists but lacks our marker; symlink = never touched, never followed.
    """
    if not os.path.lexists(path):
        return "new"
    if os.path.islink(path):
        return "symlink"
    if not os.path.isfile(path):
        return "foreign"
    existing = _read_text(path)
    if existing is None or MARKER not in existing[:_MARKER_SCAN_BYTES]:
        return "foreign"
    return "unchanged" if existing == text else "update"


def _read_text(path: str) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    except (OSError, ValueError):
        return None


def command_plan(kind: str, uid: int, paths: Sequence[str]) -> List[List[str]]:
    """The activation commands, as shown in the plan. Apply may skip the unload/restart
    steps when they do not apply (e.g. not loaded yet); it never runs anything else."""
    if kind == "launchd":
        domain = "gui/%d" % uid
        return [["launchctl", "bootout", "%s/%s" % (domain, LAUNCHD_LABEL)],
                ["launchctl", "bootstrap", domain, paths[0]]]
    return [["systemctl", "--user", "daemon-reload"],
            ["systemctl", "--user", "enable", "--now", SYSTEMD_STEM + ".timer"]]


def _warnings(config, interval_s: int, explicit_interval: bool) -> List[str]:
    out = []
    if config.hub is None:
        out.append("warning: config has no `hub`; `push` will fail each tick until it is set (%s)"
                   % config.config_path)
    if explicit_interval and interval_s != config.interval_s:
        out.append("warning: --interval %d differs from config interval_s %d; set interval_s to "
                   "%d in %s so the hub's staleness maths matches (install does not edit config)"
                   % (interval_s, config.interval_s, interval_s, config.config_path))
    return out


def log_hint(kind: str, log_path: str) -> str:
    """Where a failing tick (e.g. a push error) is logged; shown in the plan and after apply."""
    if kind == "launchd":
        return "logs: %s (stdout and stderr of each tick)" % log_path
    return "logs: journalctl --user -u %s" % SYSTEMD_STEM


def render_plan(kind: str, interval_s: int, python: str, script: str, path_env: str,
                entries: Sequence[Tuple[str, str]], commands: Sequence[Sequence[str]],
                warnings: Sequence[str], log_path: str = "") -> str:
    """Human plan text. Deterministic: depends only on its arguments."""
    lines = ["grid-fleet install plan (%s)" % ("macOS, launchd" if kind == "launchd"
                                               else "Linux, systemd --user"),
             "  interval: %d s" % interval_s,
             "  python:   %s" % python,
             "  script:   %s" % script,
             "  PATH:     %s" % path_env,
             "  each tick: collect, then push",
             "  " + log_hint(kind, log_path),
             "files:"]
    for state, path in entries:
        lines.append("  %-9s %s" % (state, path))
    lines.append("commands (unload/restart steps run only when updating an existing install):")
    for argv in commands:
        lines.append("  " + " ".join(shlex.quote(a) for a in argv))
    if kind == "systemd":
        lines.append(LINGER_NOTE)
    lines.extend(warnings)
    return "\n".join(lines) + "\n"


# --- side effects -----------------------------------------------------------------


def run_command(argv: Sequence[str]) -> Tuple[int, str]:
    """Default runner: a real subprocess. launchctl/systemctl are the only callers."""
    try:
        r = subprocess.run(list(argv), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           universal_newlines=True)
    except OSError as exc:
        return 127, "%s: %s" % (argv[0], exc.strerror or exc)
    return r.returncode, r.stdout


def _write_atomic(path: str, text: str, mode: int = 0o644) -> None:
    """Write via a temp file in the same dir + rename, so a crash never leaves half a file.

    `mode` is applied to the temp file before the rename: units are world-readable
    (0644); the statusLine code passes the existing file's own mode instead.
    """
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".grid-fleet.", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        if os.path.lexists(tmp):
            os.remove(tmp)
        raise


def _makedirs_private(path: str) -> None:
    """Like os.makedirs(exist_ok=True), but every directory THIS call creates is 0700.

    The state dir (snapshots, inbox) and the config dir hold per-user data, so a dir we
    create must not be group/world-readable. os.makedirs(mode=) only applies the mode to
    the leaf (and the umask can mask it), so each missing component is made and chmod-ed
    explicitly. A directory that already existed is never chmod-ed: its mode is the
    user's choice.
    """
    missing = []
    p = os.path.abspath(path)
    while not os.path.isdir(p):
        missing.append(p)
        parent = os.path.dirname(p)
        if parent == p:
            break
        p = parent
    for d in reversed(missing):
        try:
            os.mkdir(d, 0o700)
        except FileExistsError:
            if not os.path.isdir(d):  # a regular file in the way: same error os.makedirs gives
                raise
            continue  # created by someone else meanwhile: not ours to chmod
        os.chmod(d, 0o700)


def _tty() -> bool:
    return sys.stdin.isatty() and sys.stdout.isatty()


def _confirm(prompt: Callable[[str], str]) -> bool:
    try:
        return prompt("Proceed? [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:
        return False


def _run_checked(runner: Runner, argv: Sequence[str]) -> None:
    rc, out = runner(argv)
    if rc != 0:
        raise InstallError("`%s` failed (exit %d): %s" % (" ".join(argv), rc, out.strip()))


# --- apply / uninstall ---------------------------------------------------------------


def _is_loaded(kind, uid, runner) -> bool:
    """Read-only query: is the job/timer already registered with the scheduler?"""
    if kind == "launchd":
        return runner(["launchctl", "print", "gui/%d/%s" % (uid, LAUNCHD_LABEL)])[0] == 0
    return runner(["systemctl", "--user", "is-enabled", SYSTEMD_STEM + ".timer"])[0] == 0


def _apply(kind, entries, uid, runner, state_dir, loaded):
    """Make the system match `entries` [(state, path, text)]; `loaded` is _is_loaded().

    Ordering rule: write the new files FIRST, touch the scheduler second. If a write
    fails (read-only dir, disk full) the exception propagates before anything was
    unloaded, so an already-running job keeps running on its old definition.
    """
    changed = [e for e in entries if e[0] != "unchanged"]
    if kind == "launchd":
        _makedirs_private(state_dir)  # launchd will not create the log's directory
        for _s, path, text in changed:
            _write_atomic(path, text)
        if loaded:
            # Unload the old definition before loading the new file; best effort, the
            # bootstrap right after is the step whose failure we report.
            runner(["launchctl", "bootout", "gui/%d/%s" % (uid, LAUNCHD_LABEL)])
        _run_checked(runner, ["launchctl", "bootstrap", "gui/%d" % uid, entries[0][1]])
        return
    timer = SYSTEMD_STEM + ".timer"
    for _s, path, text in changed:
        _write_atomic(path, text)
    _run_checked(runner, ["systemctl", "--user", "daemon-reload"])
    _run_checked(runner, ["systemctl", "--user", "enable", "--now", timer])
    if loaded and changed:  # an update to a running timer: restart so the new interval applies
        _run_checked(runner, ["systemctl", "--user", "restart", timer])


def _unload_argv(kind, uid):
    if kind == "launchd":
        return ["launchctl", "bootout", "gui/%d/%s" % (uid, LAUNCHD_LABEL)]
    return ["systemctl", "--user", "disable", "--now", SYSTEMD_STEM + ".timer"]


def _uninstall(kind, paths, uid, runner, loaded):
    """Unload, then remove only files that carry our marker. Returns (messages, ok).

    ok is False when anything was left alone or any scheduler command failed. A failed
    unload never stops the file removal: the files are ours and the user asked for them
    gone; the failure is reported and the exit code is non-zero. `loaded` is
    _is_loaded(): the job is unloaded whenever the scheduler still has it, even if its
    files were already deleted by hand.
    """
    msgs, ok = [], True
    owned = []
    for path in paths:
        st = file_state(path, "")  # text irrelevant: only the owned/absent/foreign split
        if st == "new":
            continue
        if st in ("foreign", "symlink"):
            msgs.append("left alone (%s, not created by grid-fleet): %s" % (st, path))
            ok = False
        else:
            owned.append(path)
    if loaded:
        argv = _unload_argv(kind, uid)
        rc, out = runner(argv)
        if rc != 0:
            msgs.append("unload FAILED (exit %d): `%s`: %s" % (rc, " ".join(argv), out.strip()))
            ok = False
        else:
            msgs.append("unloaded")
    for path in owned:
        os.remove(path)  # a regular file with our marker; never a directory or symlink
        msgs.append("removed: " + path)
    if kind == "systemd" and (owned or loaded):
        rc, out = runner(["systemctl", "--user", "daemon-reload"])
        if rc != 0:
            msgs.append("daemon-reload FAILED (exit %d): %s" % (rc, out.strip()))
            ok = False
    return (msgs or ["nothing to remove"]), ok


# --- statusLine (task 8.3) -----------------------------------------------------------------
#
# Flow for `install --statusline`:   read settings -> build edit -> print exact
# before/after -> TTY + "y" -> backup -> save original to config -> atomic write.
# Everything up to the confirmation is read-only. Order of the writes matters:
#   1. backup of settings.json (a byte copy)
#   2. config `statusline_original` (so the original can never be lost)
#   3. settings.json itself
# A failure after step 2 leaves a harmless stale config value; a re-run overwrites it.

SETTINGS_FILE = "settings.json"
BACKUP_INFIX = ".grid-fleet-backup-"
CONFIG_KEY = "statusline_original"
# /bin/sh is what Claude Code's own command runner uses (node's default shell), so
# running the original through `sh -c` keeps its quoting, `$VAR`, `~`, `&&` and pipes
# meaning exactly what they meant before the wrap.
SHELL_ARGV = ["/bin/sh", "-c"]
_NO_STATUSLINE = "(no statusLine configured)"

# action: "change" (write new_text), "noop" (message only) or "refuse" (message, exit 1).
StatuslineEdit = collections.namedtuple(
    "StatuslineEdit", "action message path raw new_text before after note original")


def settings_path(config, env: Mapping[str, str]) -> str:
    """<claude dir>/settings.json. config.claude_dir already honours GRID_FLEET_CLAUDE_DIR
    and CLAUDE_CONFIG_DIR; the fallback uses the injected env's HOME, never the real one."""
    return os.path.join(config.claude_dir or os.path.join(_home(env), ".claude"), SETTINGS_FILE)


def tap_command(python: str, script: str, original: Optional[str]) -> str:
    """The new `statusLine.command`: `<python> <script> tap -- /bin/sh -c '<original>'`.

    The tap runs everything after `--` as an argv WITHOUT a shell (limits._run_original),
    but `statusLine.command` is a shell string. Passing the original as one quoted
    `sh -c` argument is therefore the only form that preserves its meaning for every
    original (flags, quotes, `$`, `&&`). With no original (or an empty one) the tap
    gets no command and prints nothing.
    """
    base = "%s %s tap --" % (shlex.quote(python), shlex.quote(script))
    if not original:
        return base
    return "%s %s %s" % (base, " ".join(SHELL_ARGV), shlex.quote(original))


def _tap_words(command: str) -> Optional[List[str]]:
    """The words after `tap --` if `command` is a grid-fleet tap wrapper, else None."""
    try:
        words = shlex.split(command)
    except ValueError:
        return None
    if len(words) >= 4 and os.path.basename(words[1]) == "grid-fleet" and words[2:4] == ["tap", "--"]:
        return words[4:]
    return None


def is_tap_command(command: str) -> bool:
    return _tap_words(command) is not None


def _original_from_tap(command: str) -> Optional[str]:
    """Recover the original from a wrapper we wrote (fallback when config lost it).
    Raises InstallError for a tap command whose tail is not a form we produce."""
    rest = _tap_words(command) or []
    if not rest:
        return None
    if rest[:2] == SHELL_ARGV and len(rest) == 3:
        return rest[2]
    raise InstallError("cannot tell what the original statusLine was from %r" % command)


# -- settings file I/O ---------------------------------------------------------------------

_STYLES = [(indent, ascii_, nl) for indent in (2, 4, "\t", None)
           for ascii_ in (False, True) for nl in ("\n", "")]


def _dump(data, style) -> str:
    indent, ascii_, nl = style
    return json.dumps(data, indent=indent, ensure_ascii=ascii_) + nl


def _pick_style(data, text: str):
    """Find the JSON layout that reproduces `text` byte-for-byte, so the rewrite does not
    reformat the user's file. Returns (style, exact); falls back to 2-space + newline."""
    for style in _STYLES:
        if _dump(data, style) == text:
            return style, True
    return (2, False, "\n"), False


def _read_json_object(path: str, what: str):
    """(raw bytes, parsed dict) or InstallError. Key order is kept (dicts are ordered)."""
    try:
        with open(path, "rb") as fh:
            raw = fh.read()
    except FileNotFoundError:
        raise InstallError("%s not found: %s" % (what, path))
    except OSError as exc:
        raise InstallError("cannot read %s %s: %s" % (what, path, exc.strerror or exc))
    try:
        data = json.loads(raw.decode("utf-8"))
    except ValueError as exc:  # includes UnicodeDecodeError and JSONDecodeError
        raise InstallError("%s is not valid JSON, left untouched: %s (%s)" % (what, path, exc))
    if not isinstance(data, dict):
        raise InstallError("%s is not a JSON object, left untouched: %s" % (what, path))
    return raw, data


def _mode_of(path: str) -> int:
    return os.stat(path).st_mode & 0o777


def _backup(path: str, raw: bytes) -> str:
    """Byte copy of the settings file next to it, never overwriting one.

    The backup's mode is the original's mode & 0600: settings.json can hold secrets
    (env values, tokens), so a backup is never group/world-readable even when the
    original is, and never wider than the original. (Backups are not pruned.)
    """
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(cfg.now()))
    mode = _mode_of(path) & 0o600
    for n in range(100):
        dest = "%s%s%s%s" % (path, BACKUP_INFIX, stamp, "" if n == 0 else "-%d" % n)
        try:
            fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            continue
        with os.fdopen(fd, "wb") as fh:
            fh.write(raw)
        os.chmod(dest, mode)
        return dest
    raise InstallError("could not find a free backup name for %s" % path)


def _write_json_file(path: str, data: dict, style, mode: int) -> None:
    """Atomic rewrite through symlinks: a dotfile-managed symlink stays a symlink."""
    _write_atomic(os.path.realpath(path), _dump(data, style), mode)


# -- building the edit ---------------------------------------------------------------------


def _show(value: Optional[str]) -> str:
    """Exact rendering of a command for the diff: JSON string syntax shows every escape."""
    return _NO_STATUSLINE if value is None else json.dumps(value, ensure_ascii=False)


def _statusline_command(data: dict):
    """(statusLine value, its command or None). InstallError for a shape we will not guess."""
    sl = data.get("statusLine")
    if sl is None:
        return None, None
    if (isinstance(sl, dict) and isinstance(sl.get("command"), str)
            and sl.get("type", "command") == "command"):
        return sl, sl["command"]
    raise InstallError("statusLine in settings.json has a shape grid-fleet does not handle "
                       "(expected {\"type\": \"command\", \"command\": \"...\"}); not changing it")


def plan_statusline_install(path: str, python: str, script: str) -> StatuslineEdit:
    """Read-only. The edit that wraps the current statusLine in the tap."""
    raw, data = _read_json_object(path, "settings file")
    style, exact = _pick_style(data, raw.decode("utf-8"))
    sl, current = _statusline_command(data)
    if current is not None and is_tap_command(current):
        # Never double-wrap. (If the clone moved, the old wrapper keeps pointing at the old
        # path: `--uninstall` then `--statusline` re-points it.)
        return StatuslineEdit("noop", "statusLine is already wrapped by grid-fleet; nothing "
                              "to change", path, raw, None, current, current, "", None)
    wrapped = tap_command(python, script, current)
    new_sl = {"type": "command", "command": wrapped} if sl is None else dict(sl, command=wrapped)
    new_data = dict(data)  # a copy keeps key order; an existing statusLine stays in place
    new_data["statusLine"] = new_sl
    note = "" if exact else ("note: settings.json is not in a layout grid-fleet can reproduce; "
                             "it will be rewritten as 2-space JSON (same values and key order)")
    return StatuslineEdit("change", "", path, raw, _dump(new_data, style), current, wrapped,
                          note, current)


def plan_statusline_restore(path: str, saved: Optional[str]) -> StatuslineEdit:
    """Read-only. The edit that puts the original statusLine back.

    `saved` is config statusline_original (None = unknown); when None the original is
    recovered from the wrapper itself, and a wrapper with no original means we created
    the statusLine, so it is removed again.
    """
    try:
        raw, data = _read_json_object(path, "settings file")
    except InstallError as exc:
        if not os.path.lexists(path):
            return StatuslineEdit("noop", "no settings file, nothing to restore: %s" % path,
                                  path, b"", None, None, None, "", None)
        return StatuslineEdit("refuse", "statusLine NOT restored: %s" % exc,
                              path, b"", None, None, None, "", None)
    style, exact = _pick_style(data, raw.decode("utf-8"))
    try:
        sl, current = _statusline_command(data)
    except InstallError:  # a shape we could never have written: not ours, leave it
        sl, current = None, None
    if current is None or not is_tap_command(current):
        return StatuslineEdit("noop", "statusLine is not wrapped by grid-fleet; nothing to "
                              "restore", path, raw, None, current, current, "", None)
    try:
        original = saved if saved is not None else _original_from_tap(current)
        new_data = dict(data)
        if original is None:
            # We created the whole statusLine; remove it, but only if nobody added to it.
            if set(sl) - {"type", "command"}:
                raise InstallError("statusLine has extra keys and no saved original; "
                                   "restore it by hand")
            del new_data["statusLine"]
        else:
            new_data["statusLine"] = dict(sl, command=original)
    except InstallError as exc:
        return StatuslineEdit("refuse", "statusLine NOT restored: %s" % exc, path, raw,
                              None, None, None, "", None)
    note = "" if exact else ("note: settings.json will be rewritten as 2-space JSON "
                             "(same values and key order)")
    return StatuslineEdit("change", "", path, raw, _dump(new_data, style), current,
                          original, note, original)


# -- applying ------------------------------------------------------------------------------


def _set_config_original(config_path: str, value: Optional[str], create: bool) -> None:
    """Set (or clear, value=None) `statusline_original` in the config file, keeping every
    other key. Raises InstallError if the file is unusable, OSError on write failure."""
    if os.path.lexists(config_path):
        raw, data = _read_json_object(config_path, "config file")
        style, _exact = _pick_style(data, raw.decode("utf-8"))
        mode = _mode_of(config_path)
    elif create:
        data, style, mode = {"schema": cfg.SCHEMA}, (2, False, "\n"), 0o600
    else:
        return
    data[CONFIG_KEY] = value
    # A config dir this tool has to create (first install) is private, like the file in it.
    _makedirs_private(os.path.dirname(os.path.realpath(config_path)))
    _write_json_file(config_path, data, style, mode)


def _apply_statusline_edit(edit: StatuslineEdit, config_path: str, restoring: bool) -> str:
    """Perform a confirmed edit; returns the backup path. Raises InstallError / OSError."""
    # The user (or Claude Code) may have saved settings.json while we waited for the "y".
    try:
        with open(edit.path, "rb") as fh:
            still = fh.read()
    except OSError as exc:
        raise InstallError("cannot re-read %s: %s" % (edit.path, exc.strerror or exc))
    if still != edit.raw:
        raise InstallError("%s changed while waiting for confirmation; nothing was changed, "
                           "re-run" % edit.path)
    mode = _mode_of(edit.path)
    backup = _backup(edit.path, edit.raw)
    if not restoring:
        _set_config_original(config_path, edit.original, create=True)
    _write_atomic(os.path.realpath(edit.path), edit.new_text, mode)
    if restoring:
        # Settings are already right; clearing the saved value is housekeeping.
        try:
            _set_config_original(config_path, None, create=False)
        except (InstallError, OSError) as exc:
            sys.stderr.write("grid-fleet install: statusLine restored, but could not clear "
                             "%s in the config: %s\n" % (CONFIG_KEY, exc))
    return backup


def _print_edit(edit: StatuslineEdit, config_path: str, restoring: bool) -> None:
    """The exact before/after the user is asked to confirm."""
    out = sys.stdout
    out.write("%s\n  settings: %s\n  statusLine.command\n    before: %s\n    after:  %s\n"
              % ("statusLine restore" if restoring else "grid-fleet install --statusline",
                 edit.path, _show(edit.before),
                 "(statusLine removed)" if edit.after is None else _show(edit.after)))
    out.write("  all other settings: unchanged\n")
    out.write("  backup: %s<UTC time> (written first)\n" % (edit.path + BACKUP_INFIX))
    if not restoring:
        out.write("  original saved to %s as %s\n" % (config_path, CONFIG_KEY))
    if edit.note:
        out.write("  %s\n" % edit.note)


def _statusline_main(config, args, explicit_interval, env, runner, python, script, uid,
                     is_tty, prompt) -> int:
    """`install --statusline [--uninstall]`: the statusLine half only, no timers touched."""
    if explicit_interval is not None:
        sys.stderr.write("grid-fleet install: --interval does not apply to --statusline\n")
        return EXIT_USAGE
    if getattr(args, "uninstall", False):
        sl = plan_statusline_restore(settings_path(config, env), _saved_original(config))
        return _run_uninstall(None, [], uid, runner, is_tty, prompt, sl, config.config_path,
                              timers=False)
    if not python or not os.path.isabs(python) or not os.path.isabs(script):
        sys.stderr.write("grid-fleet install: need absolute paths for python and script "
                         "(got %r, %r)\n" % (python, script))
        return EXIT_USAGE
    return _statusline_install(config, env, python, script, is_tty, prompt)


def _statusline_install(config, env, python, script, is_tty, prompt) -> int:
    path = settings_path(config, env)
    try:
        edit = plan_statusline_install(path, python, script)
        if os.path.lexists(config.config_path):  # fail now, not after the "y"
            _read_json_object(config.config_path, "config file")
    except InstallError as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    if edit.action == "noop":
        sys.stdout.write("%s\n" % edit.message)
        return EXIT_OK
    _print_edit(edit, config.config_path, restoring=False)
    if not is_tty():
        sys.stderr.write("grid-fleet install: --statusline needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    try:
        backup = _apply_statusline_edit(edit, config.config_path, restoring=False)
    except (InstallError, OSError) as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    sys.stdout.write("statusLine now runs the tap\nbackup: %s\nundo: grid-fleet install "
                     "--uninstall\n" % backup)
    return EXIT_OK


