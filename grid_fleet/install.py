def install_main(config, args, *, runner: Optional[Runner] = None,
                 env: Optional[Mapping[str, str]] = None, platform: Optional[str] = None,
                 python: Optional[str] = None, script: Optional[str] = None,
                 uid: Optional[int] = None, is_tty: Optional[Callable[[], bool]] = None,
                 prompt: Optional[Callable[[str], str]] = None) -> int:
    """`grid-fleet install`. Keyword-only parameters exist so tests can inject every
    side effect (runner, env, platform, tty, prompt); cli.py passes none of them.

    Exit: 0 ok / plan printed; 1 refused or failed; 2 bad --interval or platform.
    """
    runner = runner or run_command
    env = os.environ if env is None else env
    is_tty = is_tty or _tty
    prompt = prompt or input
    python = python or sys.executable
    script = script or default_script()
    uid = os.getuid() if uid is None else uid

    explicit = getattr(args, "interval", None)
    explicit_hub = getattr(args, "hub", None)
    explicit_account = getattr(args, "account", None)
    uninstall = bool(getattr(args, "uninstall", False))
    if (getattr(args, "statusline", False) or uninstall) and (
            explicit_hub is not None or explicit_account is not None):
        # --statusline and --uninstall never write hub/account; accepting the flags and
        # ignoring them would look like they had been applied.
        sys.stderr.write("grid-fleet install: --hub and --account only apply to the timer "
                         "install, not to --statusline or --uninstall\n")
        return EXIT_USAGE
    if getattr(args, "statusline", False):
        return _statusline_main(config, args, explicit, env, runner, python, script, uid,
                                is_tty, prompt)
    interval_s = explicit if explicit is not None else config.interval_s
    if interval_s not in cfg.ALLOWED_INTERVALS:  # also guards programmatic callers
        sys.stderr.write("grid-fleet install: interval must be one of %s (got %r)\n"
                         % (", ".join(map(str, cfg.ALLOWED_INTERVALS)), interval_s))
        return EXIT_USAGE
    # Programmatic callers bypass argparse, so re-check the flag values here.
    for flag, value, check in (("--hub", explicit_hub, push.validate_hub),
                               ("--account", explicit_account, validate_account)):
        reason = check(value) if value is not None else None
        if reason is not None:
            sys.stderr.write("grid-fleet install: invalid %s %r: %s\n" % (flag, value, reason))
            return EXIT_USAGE
    try:
        kind = system_kind(platform if platform is not None else sys.platform)
        if not python or not os.path.isabs(python) or not os.path.isabs(script):
            raise InstallError("need absolute paths for python and script (got %r, %r)"
                               % (python, script))
        path_env = env.get("PATH") or FALLBACK_PATH
        log_path = os.path.join(config.state_dir, "timer.log")
        files = render_files(kind, python=python, script=script, path_env=path_env,
                             interval_s=interval_s, env=env, log_path=log_path)
    except InstallError as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_USAGE

    paths = [p for p, _t in files]
    entries = [(file_state(p, t), p, t) for p, t in files]
    mode_change = bool(getattr(args, "apply", False))

    if uninstall:
        # NOTE: uninstall deliberately leaves interval_s / hub / account in the config.
        # They are the user's settings (and harmless without a timer); only the files
        # install created and the saved statusLine are undone.
        sl = plan_statusline_restore(settings_path(config, env), _saved_original(config))
        return _run_uninstall(kind, paths, uid, runner, is_tty, prompt, sl, config.config_path)

    # Effective config values: the flag wins, else what the config already holds.
    hub = explicit_hub if explicit_hub is not None else config.hub
    account = explicit_account if explicit_account is not None else config.account
    account_problem = validate_account(account)
    if account_problem is not None:  # a bad value already stored in the config
        sys.stderr.write("grid-fleet install: config account %r is not usable (%s); pass a "
                         "valid --account\n" % (account, account_problem))
        return EXIT_USAGE
    hub_problem = push.validate_hub(hub) if hub is not None else None
    # Read-only: decides what would be written. A config we must not touch (invalid JSON,
    # unknown schema) stops everything here, in plan mode too, so the plan is never a lie.
    cfg_edit = None
    if hub is not None and hub_problem is None:
        try:
            cfg_edit = plan_config_edit(config, interval_s, hub, account)
        except InstallError as exc:
            sys.stderr.write("grid-fleet install: %s\n" % exc)
            return EXIT_REFUSED

    plan = render_plan(kind, interval_s, python, script, path_env,
                       [(s, p) for s, p, _t in entries], command_plan(kind, uid, paths),
                       _warnings(config.config_path, hub, hub_problem)
                       + claude_warning(cfg.claude_bin(env), path_env), log_path,
                       config_plan_lines(cfg_edit) if cfg_edit is not None else ())
    sys.stdout.write(plan)
    if not mode_change:
        sys.stdout.write("plan only: nothing was changed. Re-run with --apply to install.\n")
        return EXIT_OK

    # Apply from here. No usable hub comes first, before the TTY check: without a hub every
    # push tick would fail, so installing the timer is never what the user wants.
    if cfg_edit is None:
        if hub is None:
            sys.stderr.write("grid-fleet install: --apply needs a hub: pass --hub ALIAS (or "
                             "`local`) or set the `hub` key in %s; nothing was changed\n"
                             % config.config_path)
        else:
            sys.stderr.write("grid-fleet install: hub %s is not usable (%s); pass a valid "
                             "--hub; nothing was changed\n" % (json.dumps(hub), hub_problem))
        return EXIT_REFUSED
    # Non-TTY next: spec says print plan, exit non-zero, modify nothing.
    if not is_tty():
        sys.stderr.write("grid-fleet install: --apply needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    blocked = [(s, p) for s, p, _t in entries if s in ("foreign", "symlink")]
    if blocked:
        for s, p in blocked:
            sys.stderr.write("grid-fleet install: refusing to touch %s (%s, not created by "
                             "grid-fleet); move it aside first\n" % (p, s))
        return EXIT_REFUSED
    loaded = _is_loaded(kind, uid, runner)
    timer_current = loaded and all(s == "unchanged" for s, _p, _t in entries)
    if timer_current and not cfg_edit.changed:
        sys.stdout.write("nothing to change\n")  # second run with the same inputs
        return EXIT_OK
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    # Config BEFORE the timer: the first tick (which can fire as soon as the timer is
    # loaded) must already see the right hub and interval_s.
    config_written = False
    try:
        if cfg_edit.changed:
            _apply_config_edit(cfg_edit)
            config_written = True
        if not timer_current:
            _apply(kind, entries, uid, runner, config.state_dir, loaded)
    except (InstallError, OSError) as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        if config_written:
            # The scheduler step failed after the config was already on disk: say so, or the
            # user thinks nothing happened. Re-running is safe: the config then compares
            # equal, and the timer files are rewritten / reloaded as needed.
            sys.stderr.write("grid-fleet install: the config was already written (%s); "
                             "re-running the same command is safe and repairs the timer\n"
                             % cfg_edit.path)
        return EXIT_REFUSED
    if cfg_edit.changed:
        sys.stdout.write("config written: %s\n" % cfg_edit.path)
    if timer_current:
        # Config-only change: the loaded timer was left alone, so "installed" and the
        # log/linger hints (about a timer we did not touch) would be inaccurate.
        sys.stdout.write("config updated; timer unchanged\n")
        return EXIT_OK
    sys.stdout.write("installed\n%s\n" % log_hint(kind, log_path))
    if kind == "systemd":
        sys.stdout.write(LINGER_NOTE + "\n")
    return EXIT_OK


def _saved_original(config) -> Optional[str]:
    """statusline_original as saved in the config FILE, falling back to the loaded Config
    when the file is gone. None means "unknown / none". It is one slot shared by every
    Claude dir, so plan_statusline_restore only cross-checks against it; the original
    embedded in the wrapper decides."""
    try:
        _raw, data = _read_json_object(config.config_path, "config file")
    except InstallError:
        value = config.statusline_original
    else:
        value = data.get(CONFIG_KEY)
    return value if isinstance(value, str) else None


def _run_uninstall(kind, paths, uid, runner, is_tty, prompt, sl, config_path, timers=True) -> int:
    """--uninstall: show what would go, confirm once, then remove owned timer files and
    restore the statusLine. `sl` is a plan_statusline_restore() edit; timers=False limits
    the run to the statusLine (`--statusline --uninstall`)."""
    present = [(file_state(p, ""), p) for p in paths] if timers else []
    # Read-only query, so a job whose files were deleted by hand is still found.
    loaded = _is_loaded(kind, uid, runner) if timers else False
    sys.stdout.write("grid-fleet uninstall plan (%s)\n" % (kind if timers else "statusLine only"))
    for state, p in present:
        what = {"new": "absent", "unchanged": "remove", "update": "remove"}.get(state, "leave (%s)" % state)
        sys.stdout.write("  %-14s %s\n" % (what, p))
    if loaded:
        sys.stdout.write("  %-14s %s\n" % ("unload", " ".join(_unload_argv(kind, uid))))
    if sl.action == "change":
        _print_edit(sl, config_path, restoring=True)
    else:
        sys.stdout.write("  statusLine: %s\n" % sl.message)
    timers_work = loaded or any(s != "new" for s, _p in present)
    if not (timers_work or sl.action == "change"):
        sys.stdout.write("nothing to remove\n")
        return EXIT_REFUSED if sl.action == "refuse" else EXIT_OK
    if not is_tty():
        sys.stderr.write("grid-fleet install: --uninstall needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    msgs, ok = [], sl.action != "refuse"
    if timers:
        try:
            msgs, ok_t = _uninstall(kind, paths, uid, runner, loaded)
            ok = ok and ok_t
        except OSError as exc:
            sys.stderr.write("grid-fleet install: %s\n" % exc)
            return EXIT_REFUSED
    if sl.action == "change":
        try:
            msgs.append("statusLine restored; backup: %s"
                        % _apply_statusline_edit(sl, config_path, restoring=True))
        except (InstallError, OSError, ValueError) as exc:
            msgs.append("statusLine NOT restored: %s" % exc)
            ok = False
    for m in msgs:
        sys.stdout.write(m + "\n")
    return EXIT_OK if ok else EXIT_REFUSED
