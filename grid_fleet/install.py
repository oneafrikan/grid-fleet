"""Timer install for `grid-fleet install` (Group 8, timers only).

Owner: Group 8 unit (core-platform-engineer). Entry point used by cli.py:
install_main(config, args) -> int. OS-specific code is isolated here
(CLAUDE.md hard constraint).

What this module does
---------------------
  macOS : one user LaunchAgent plist under ~/Library/LaunchAgents, loaded with
          `launchctl bootstrap`.
  Linux : one user .service + .timer under the user systemd dir, enabled with
          `systemctl --user enable --now`. `loginctl enable-linger` is only
          ever PRINTED as a note, never run.
  Each tick runs `collect` then `push` (push only if collect succeeded).

What it deliberately does NOT do (yet)
--------------------------------------
  `install --statusline` / restoring the statusLine on uninstall (task 8.3)
  waits for the Group 7 tap. Nothing here reads or writes ~/.claude.
  Writing hub/account into the config file is also not done here: `--interval`
  only affects the timer (see the mismatch warning in `_warnings`).

Safety model
------------
  * Default is PLAN: prints files + commands, changes nothing, runs nothing.
  * `--apply` and `--uninstall` need an interactive TTY and a "y" answer.
  * Render functions are pure (return text) and unit-tested. The only side
    effects are file writes/removals under the user's own unit dirs and calls
    to `launchctl`/`systemctl` through an injectable runner.
  * Every file we write starts with a generated-file marker. We only ever
    overwrite or delete a file that carries the marker, and never a symlink:
    a foreign file or symlink at our path is reported and left alone.
  * No root: everything is per-user.
"""

import argparse
import os
import plistlib
import shlex
import subprocess
import sys
import tempfile
from typing import Callable, List, Mapping, Optional, Sequence, Tuple

from grid_fleet import config as cfg

# Reverse-DNS style label for the launchd job; also the file stem on macOS.
LAUNCHD_LABEL = "io.grid-fleet.timer"
# systemd unit stem: grid-fleet.service / grid-fleet.timer.
SYSTEMD_STEM = "grid-fleet"

# First line(s) of every file we write. Presence of this string is the ONLY thing
# that lets us overwrite or delete a file (ownership test).
MARKER = "Generated by grid-fleet install"
_MARKER_SCAN_BYTES = 1024

# Used if PATH is unset at install time: the scheduler's own minimal default.
FALLBACK_PATH = "/usr/bin:/bin"
# First tick after the timer starts (Linux). Later ticks follow `interval_s`.
FIRST_RUN_DELAY_S = 30

EXIT_OK = 0
EXIT_REFUSED = 1  # non-TTY, declined, foreign file in the way, command failed
EXIT_USAGE = 2    # bad --interval, unsupported platform

LINGER_NOTE = (
    "note: on Linux the user systemd manager stops when you log out, so the timer "
    "only runs while you are logged in unless lingering is enabled. To keep it "
    "running while logged out (headless boxes), run once yourself: "
    "`loginctl enable-linger $USER`. grid-fleet never runs this."
)

# Runner contract: argv -> (returncode, combined output). Never raises for a
# missing binary: returns 127 so callers treat it as a failed command.
Runner = Callable[[Sequence[str]], Tuple[int, str]]


class InstallError(Exception):
    """User-facing install problem; message goes to stderr."""


# --- pure rendering -----------------------------------------------------------


def _check_text(label: str, value: str) -> str:
    """Reject values that could break out of a unit/plist line (newlines, NULs)."""
    if any(ord(c) < 32 for c in value):
        raise InstallError("%s contains a control character; refusing to write it" % label)
    return value


def _marker_line() -> str:
    return "%s; do not edit; regenerate by re-running `grid-fleet install` with apply." % MARKER


def _tick_command(python: str, script: str) -> str:
    """Shell form of one tick: collect, then push only if collect succeeded."""
    base = "%s %s" % (shlex.quote(python), shlex.quote(script))
    return "%s collect && %s push" % (base, base)


def render_launchd_plist(python: str, script: str, path_env: str, interval_s: int,
                         log_path: str) -> str:
    """The LaunchAgent plist as text. Pure; plistlib output is deterministic (sorted keys).

    ProgramArguments uses an absolute /bin/sh so `collect && push` needs no PATH
    lookup; the interpreter and script are absolute too. PATH is the install-time
    value so `ssh` and `claude` resolve under launchd's minimal environment.
    """
    for label, value in (("python", python), ("script", script), ("PATH", path_env),
                         ("log path", log_path)):
        _check_text(label, value)
    body = plistlib.dumps({
        "Label": LAUNCHD_LABEL,
        "ProgramArguments": ["/bin/sh", "-c", _tick_command(python, script)],
        "StartInterval": interval_s,
        # Run once at load too, so a fresh install shows up on the hub immediately.
        "RunAtLoad": True,
        "EnvironmentVariables": {"PATH": path_env},
        # launchd has no journal: keep stderr (push failures) where the user can find it.
        "StandardOutPath": log_path,
        "StandardErrorPath": log_path,
    }).decode("utf-8")
    # XML comment between the DOCTYPE and <plist> carries the ownership marker.
    return body.replace("<plist ", "<!-- %s -->\n<plist " % _marker_line(), 1)


def _sd_arg(value: str) -> str:
    """Quote one ExecStart= word. systemd expands `%` specifiers and `$` vars there."""
    esc = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    if any(c.isspace() or c in "'\"" for c in value):
        return '"%s"' % esc
    return esc


def render_systemd_service(python: str, script: str, path_env: str) -> str:
    """The user .service. Type=oneshot with two ExecStart lines runs them in order and
    stops at the first failure, which is the same collect-then-push-if-ok rule as launchd."""
    for label, value in (("python", python), ("script", script), ("PATH", path_env)):
        _check_text(label, value)
    py, sc = _sd_arg(python), _sd_arg(script)
    # Environment= takes the whole assignment quoted; only `%`, `\` and `"` are special.
    env = ("PATH=" + path_env).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return "\n".join([
        "# " + _marker_line(),
        "[Unit]",
        "Description=grid-fleet: collect and push a snapshot",
        "",
        "[Service]",
        "Type=oneshot",
        'Environment="%s"' % env,
        "ExecStart=%s %s collect" % (py, sc),
        "ExecStart=%s %s push" % (py, sc),
        "",
    ])


def render_systemd_timer(interval_s: int) -> str:
    """The user .timer. OnActiveSec fires the first run shortly after the timer starts
    (OnUnitActiveSec alone would never fire: it counts from the service's last run)."""
    return "\n".join([
        "# " + _marker_line(),
        "[Unit]",
        "Description=grid-fleet: run collect and push every %d s" % interval_s,
        "",
        "[Timer]",
        "OnActiveSec=%ds" % FIRST_RUN_DELAY_S,
        "OnUnitActiveSec=%ds" % interval_s,
        "Unit=%s.service" % SYSTEMD_STEM,
        "",
        "[Install]",
        "WantedBy=timers.target",
        "",
    ])


# --- paths / plan ---------------------------------------------------------------


def _home(env: Mapping[str, str]) -> str:
    return env.get("HOME") or os.path.expanduser("~")


def systemd_user_dir(env: Mapping[str, str]) -> str:
    # XDG spec: only an absolute XDG_CONFIG_HOME counts.
    xdg = env.get("XDG_CONFIG_HOME", "")
    base = xdg if xdg and os.path.isabs(xdg) else os.path.join(_home(env), ".config")
    return os.path.join(base, "systemd", "user")


def launchd_dir(env: Mapping[str, str]) -> str:
    return os.path.join(_home(env), "Library", "LaunchAgents")


def default_script() -> str:
    """Absolute path of bin/grid-fleet in the clone this module was imported from."""
    root = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
    return os.path.join(root, "bin", "grid-fleet")


def system_kind(platform: str) -> str:
    """Map sys.platform to 'launchd' / 'systemd'; anything else is unsupported."""
    if platform == "darwin":
        return "launchd"
    if platform.startswith("linux"):
        return "systemd"
    raise InstallError("unsupported platform %r (macOS and Linux only)" % platform)


def render_files(kind: str, *, python: str, script: str, path_env: str, interval_s: int,
                 env: Mapping[str, str], log_path: str) -> List[Tuple[str, str]]:
    """[(absolute path, text)] for every file the install owns on this platform."""
    if kind == "launchd":
        return [(os.path.join(launchd_dir(env), LAUNCHD_LABEL + ".plist"),
                 render_launchd_plist(python, script, path_env, interval_s, log_path))]
    d = systemd_user_dir(env)
    return [
        (os.path.join(d, SYSTEMD_STEM + ".service"),
         render_systemd_service(python, script, path_env)),
        (os.path.join(d, SYSTEMD_STEM + ".timer"), render_systemd_timer(interval_s)),
    ]


def file_state(path: str, text: str) -> str:
    """new | unchanged | update | foreign | symlink  (read-only).

    foreign = exists but lacks our marker; symlink = never touched, never followed.
    """
    if not os.path.lexists(path):
        return "new"
    if os.path.islink(path):
        return "symlink"
    if not os.path.isfile(path):
        return "foreign"
    existing = _read_text(path)
    if existing is None or MARKER not in existing[:_MARKER_SCAN_BYTES]:
        return "foreign"
    return "unchanged" if existing == text else "update"


def _read_text(path: str) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    except (OSError, ValueError):
        return None


def command_plan(kind: str, uid: int, paths: Sequence[str]) -> List[List[str]]:
    """The activation commands, as shown in the plan. Apply may skip the unload/restart
    steps when they do not apply (e.g. not loaded yet); it never runs anything else."""
    if kind == "launchd":
        domain = "gui/%d" % uid
        return [["launchctl", "bootout", "%s/%s" % (domain, LAUNCHD_LABEL)],
                ["launchctl", "bootstrap", domain, paths[0]]]
    return [["systemctl", "--user", "daemon-reload"],
            ["systemctl", "--user", "enable", "--now", SYSTEMD_STEM + ".timer"]]


def _warnings(config, interval_s: int, explicit_interval: bool) -> List[str]:
    out = []
    if config.hub is None:
        out.append("warning: config has no `hub`; `push` will fail each tick until it is set (%s)"
                   % config.config_path)
    if explicit_interval and interval_s != config.interval_s:
        out.append("warning: --interval %d differs from config interval_s %d; set interval_s to "
                   "%d in %s so the hub's staleness maths matches (install does not edit config)"
                   % (interval_s, config.interval_s, interval_s, config.config_path))
    return out


def log_hint(kind: str, log_path: str) -> str:
    """Where a failing tick (e.g. a push error) is logged; shown in the plan and after apply."""
    if kind == "launchd":
        return "logs: %s (stdout and stderr of each tick)" % log_path
    return "logs: journalctl --user -u %s" % SYSTEMD_STEM


def render_plan(kind: str, interval_s: int, python: str, script: str, path_env: str,
                entries: Sequence[Tuple[str, str]], commands: Sequence[Sequence[str]],
                warnings: Sequence[str], log_path: str = "") -> str:
    """Human plan text. Deterministic: depends only on its arguments."""
    lines = ["grid-fleet install plan (%s)" % ("macOS, launchd" if kind == "launchd"
                                               else "Linux, systemd --user"),
             "  interval: %d s" % interval_s,
             "  python:   %s" % python,
             "  script:   %s" % script,
             "  PATH:     %s" % path_env,
             "  each tick: collect, then push",
             "  " + log_hint(kind, log_path),
             "files:"]
    for state, path in entries:
        lines.append("  %-9s %s" % (state, path))
    lines.append("commands (unload/restart steps run only when updating an existing install):")
    for argv in commands:
        lines.append("  " + " ".join(shlex.quote(a) for a in argv))
    if kind == "systemd":
        lines.append(LINGER_NOTE)
    lines.extend(warnings)
    return "\n".join(lines) + "\n"


# --- side effects -----------------------------------------------------------------


def run_command(argv: Sequence[str]) -> Tuple[int, str]:
    """Default runner: a real subprocess. launchctl/systemctl are the only callers."""
    try:
        r = subprocess.run(list(argv), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           universal_newlines=True)
    except OSError as exc:
        return 127, "%s: %s" % (argv[0], exc.strerror or exc)
    return r.returncode, r.stdout


def _write_atomic(path: str, text: str) -> None:
    """Write via a temp file in the same dir + rename, so a crash never leaves half a unit."""
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".grid-fleet.", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        if os.path.lexists(tmp):
            os.remove(tmp)
        raise


def _tty() -> bool:
    return sys.stdin.isatty() and sys.stdout.isatty()


def _confirm(prompt: Callable[[str], str]) -> bool:
    try:
        return prompt("Proceed? [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:
        return False


def _run_checked(runner: Runner, argv: Sequence[str]) -> None:
    rc, out = runner(argv)
    if rc != 0:
        raise InstallError("`%s` failed (exit %d): %s" % (" ".join(argv), rc, out.strip()))


# --- apply / uninstall ---------------------------------------------------------------


def _is_loaded(kind, uid, runner) -> bool:
    """Read-only query: is the job/timer already registered with the scheduler?"""
    if kind == "launchd":
        return runner(["launchctl", "print", "gui/%d/%s" % (uid, LAUNCHD_LABEL)])[0] == 0
    return runner(["systemctl", "--user", "is-enabled", SYSTEMD_STEM + ".timer"])[0] == 0


def _apply(kind, entries, uid, runner, state_dir, loaded):
    """Make the system match `entries` [(state, path, text)]; `loaded` is _is_loaded().

    Ordering rule: write the new files FIRST, touch the scheduler second. If a write
    fails (read-only dir, disk full) the exception propagates before anything was
    unloaded, so an already-running job keeps running on its old definition.
    """
    changed = [e for e in entries if e[0] != "unchanged"]
    if kind == "launchd":
        os.makedirs(state_dir, exist_ok=True)  # launchd will not create the log's directory
        for _s, path, text in changed:
            _write_atomic(path, text)
        if loaded:
            # Unload the old definition before loading the new file; best effort, the
            # bootstrap right after is the step whose failure we report.
            runner(["launchctl", "bootout", "gui/%d/%s" % (uid, LAUNCHD_LABEL)])
        _run_checked(runner, ["launchctl", "bootstrap", "gui/%d" % uid, entries[0][1]])
        return
    timer = SYSTEMD_STEM + ".timer"
    for _s, path, text in changed:
        _write_atomic(path, text)
    _run_checked(runner, ["systemctl", "--user", "daemon-reload"])
    _run_checked(runner, ["systemctl", "--user", "enable", "--now", timer])
    if loaded and changed:  # an update to a running timer: restart so the new interval applies
        _run_checked(runner, ["systemctl", "--user", "restart", timer])


def _unload_argv(kind, uid):
    if kind == "launchd":
        return ["launchctl", "bootout", "gui/%d/%s" % (uid, LAUNCHD_LABEL)]
    return ["systemctl", "--user", "disable", "--now", SYSTEMD_STEM + ".timer"]


def _uninstall(kind, paths, uid, runner, loaded):
    """Unload, then remove only files that carry our marker. Returns (messages, ok).

    ok is False when anything was left alone or any scheduler command failed. A failed
    unload never stops the file removal: the files are ours and the user asked for them
    gone; the failure is reported and the exit code is non-zero. `loaded` is
    _is_loaded(): the job is unloaded whenever the scheduler still has it, even if its
    files were already deleted by hand.
    """
    msgs, ok = [], True
    owned = []
    for path in paths:
        st = file_state(path, "")  # text irrelevant: only the owned/absent/foreign split
        if st == "new":
            continue
        if st in ("foreign", "symlink"):
            msgs.append("left alone (%s, not created by grid-fleet): %s" % (st, path))
            ok = False
        else:
            owned.append(path)
    if loaded:
        argv = _unload_argv(kind, uid)
        rc, out = runner(argv)
        if rc != 0:
            msgs.append("unload FAILED (exit %d): `%s`: %s" % (rc, " ".join(argv), out.strip()))
            ok = False
        else:
            msgs.append("unloaded")
    for path in owned:
        os.remove(path)  # a regular file with our marker; never a directory or symlink
        msgs.append("removed: " + path)
    if kind == "systemd" and (owned or loaded):
        rc, out = runner(["systemctl", "--user", "daemon-reload"])
        if rc != 0:
            msgs.append("daemon-reload FAILED (exit %d): %s" % (rc, out.strip()))
            ok = False
    return (msgs or ["nothing to remove"]), ok


# --- CLI ---------------------------------------------------------------------------------


def _interval_arg(raw: str) -> int:
    try:
        val = int(raw)
    except ValueError:
        val = None
    if val not in cfg.ALLOWED_INTERVALS:
        raise argparse.ArgumentTypeError(
            "interval must be one of %s (got %r)" % (", ".join(map(str, cfg.ALLOWED_INTERVALS)), raw))
    return val


def add_arguments(parser) -> None:
    """Declare install's own flags (called by cli.py for `install` only)."""
    parser.add_argument("--interval", type=_interval_arg, default=None, metavar="SECONDS",
                        help="timer interval: one of %s (default: config interval_s)"
                        % ", ".join(map(str, cfg.ALLOWED_INTERVALS)))
    parser.add_argument("--apply", action="store_true",
                        help="perform the plan after an interactive y/N (default: print only)")
    parser.add_argument("--uninstall", action="store_true",
                        help="unload and remove the timer files this tool created")


def install_main(config, args, *, runner: Optional[Runner] = None,
                 env: Optional[Mapping[str, str]] = None, platform: Optional[str] = None,
                 python: Optional[str] = None, script: Optional[str] = None,
                 uid: Optional[int] = None, is_tty: Optional[Callable[[], bool]] = None,
                 prompt: Optional[Callable[[str], str]] = None) -> int:
    """`grid-fleet install`. Keyword-only parameters exist so tests can inject every
    side effect (runner, env, platform, tty, prompt); cli.py passes none of them.

    Exit: 0 ok / plan printed; 1 refused or failed; 2 bad --interval or platform.
    """
    runner = runner or run_command
    env = os.environ if env is None else env
    is_tty = is_tty or _tty
    prompt = prompt or input
    python = python or sys.executable
    script = script or default_script()
    uid = os.getuid() if uid is None else uid

    explicit = getattr(args, "interval", None)
    interval_s = explicit if explicit is not None else config.interval_s
    if interval_s not in cfg.ALLOWED_INTERVALS:  # also guards programmatic callers
        sys.stderr.write("grid-fleet install: interval must be one of %s (got %r)\n"
                         % (", ".join(map(str, cfg.ALLOWED_INTERVALS)), interval_s))
        return EXIT_USAGE
    try:
        kind = system_kind(platform if platform is not None else sys.platform)
        if not python or not os.path.isabs(python) or not os.path.isabs(script):
            raise InstallError("need absolute paths for python and script (got %r, %r)"
                               % (python, script))
        path_env = env.get("PATH") or FALLBACK_PATH
        log_path = os.path.join(config.state_dir, "timer.log")
        files = render_files(kind, python=python, script=script, path_env=path_env,
                             interval_s=interval_s, env=env, log_path=log_path)
    except InstallError as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_USAGE

    paths = [p for p, _t in files]
    entries = [(file_state(p, t), p, t) for p, t in files]
    mode_change = bool(getattr(args, "apply", False))
    uninstall = bool(getattr(args, "uninstall", False))

    if uninstall:
        return _run_uninstall(kind, paths, uid, runner, is_tty, prompt)

    plan = render_plan(kind, interval_s, python, script, path_env,
                       [(s, p) for s, p, _t in entries], command_plan(kind, uid, paths),
                       _warnings(config, interval_s, explicit is not None), log_path)
    sys.stdout.write(plan)
    if not mode_change:
        sys.stdout.write("plan only: nothing was changed. Re-run with --apply to install.\n")
        return EXIT_OK

    # Apply from here. Non-TTY first: spec says print plan, exit non-zero, modify nothing.
    if not is_tty():
        sys.stderr.write("grid-fleet install: --apply needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    blocked = [(s, p) for s, p, _t in entries if s in ("foreign", "symlink")]
    if blocked:
        for s, p in blocked:
            sys.stderr.write("grid-fleet install: refusing to touch %s (%s, not created by "
                             "grid-fleet); move it aside first\n" % (p, s))
        return EXIT_REFUSED
    loaded = _is_loaded(kind, uid, runner)
    if loaded and all(s == "unchanged" for s, _p, _t in entries):
        sys.stdout.write("nothing to change\n")  # second run with the same inputs
        return EXIT_OK
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    try:
        _apply(kind, entries, uid, runner, config.state_dir, loaded)
    except (InstallError, OSError) as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    sys.stdout.write("installed\n%s\n" % log_hint(kind, log_path))
    if kind == "systemd":
        sys.stdout.write(LINGER_NOTE + "\n")
    return EXIT_OK


def _run_uninstall(kind, paths, uid, runner, is_tty, prompt) -> int:
    """--uninstall: show what would go, confirm, then remove owned files only."""
    present = [(file_state(p, ""), p) for p in paths]
    # Read-only query, so a job whose files were deleted by hand is still found.
    loaded = _is_loaded(kind, uid, runner)
    sys.stdout.write("grid-fleet uninstall plan (%s)\n" % kind)
    for state, p in present:
        what = {"new": "absent", "unchanged": "remove", "update": "remove"}.get(state, "leave (%s)" % state)
        sys.stdout.write("  %-14s %s\n" % (what, p))
    if loaded:
        sys.stdout.write("  %-14s %s\n" % ("unload", " ".join(_unload_argv(kind, uid))))
    if all(s == "new" for s, _p in present) and not loaded:
        sys.stdout.write("nothing to remove\n")
        return EXIT_OK
    if not is_tty():
        sys.stderr.write("grid-fleet install: --uninstall needs an interactive terminal to "
                         "confirm; nothing was changed\n")
        return EXIT_REFUSED
    if not _confirm(prompt):
        sys.stdout.write("declined: nothing was changed\n")
        return EXIT_REFUSED
    try:
        msgs, ok = _uninstall(kind, paths, uid, runner, loaded)
    except OSError as exc:
        sys.stderr.write("grid-fleet install: %s\n" % exc)
        return EXIT_REFUSED
    for m in msgs:
        sys.stdout.write(m + "\n")
    return EXIT_OK if ok else EXIT_REFUSED
